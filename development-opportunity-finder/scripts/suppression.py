"""Do-not-contact (suppression) list, kept across runs and applied to every list.

File format (CSV): phone, address, owner, date, channel, reason
  phone    a number that must not be called or texted (any format)
  address  a mailing or property address that must not get mail
  owner    an owner name that must not be contacted
  date     when it was added (YYYY-MM-DD)
  channel  all | mail | call | sms   (blank = all)
  reason   free text ("replied STOP", "asked not to be called", "deceased", ...)

Fill in phone, address or owner (one is enough). Phones are matched on their 10 digits, so
(919) 555-0134, 9195550134 and +19195550134 are the same number. Addresses are normalised
(123 Main Street = 123 MAIN ST; ZIP+4 cut to 5 digits).

Drop folder: every CSV in the project's suppress/ folder is read on every run. Freshness is judged by the
date each export was GENERATED by the system it came from, never by the file's date on disk (an old
export copied in today is still old). The kit reads that date from the file itself when it has one (a
first line like "# exported: 2026-11-18", or an export_date / exported_at / generated_at column), or
from the date you entered when you imported it:
  PY scripts/suppression.py import my_crm_optouts.csv --export-date 2026-11-18 --source "CRM" --by "Pat"
A file with no generated date counts as not current. START_HERE holds every phone and text output
(fails closed) unless at least one system export was generated in the last 7 days.
A header-only CSV imported with --export-date records "this system had no opt-outs on that date".

Retention: keep this list (and the dates) for as long as you market, and at least 5 years
(the federal Telemarketing Sales Rule record-keeping period). The pipeline keeps a master copy in
<output>/state/suppression.csv: every --suppress file and every STOP reply you pass
(--stop-replies) is merged into it, and it is applied on every later run, even if you
forget the flag. Suppression is cumulative: every run adds to the master list and nothing is
ever taken off it by the kit (a run that would leave fewer rows than before stops with an error).
Never remove a suppression row. If someone later asks to hear from you again, keep the row and
handle it with your counsel.

Where requests come from: import the latest opt-outs and do-not-contact requests from every system
where your team communicates with these owners (CRM, dialer, texting tool, email, mail house). Log a manual
request (a call, letter, email or in-person "don't contact me" an employee received) with:
  PY scripts/suppression.py add --phone "(919) 555-0134" --owner "Pat Lee" --reason "asked on a call" --by "Sam"
It is appended to suppress/manual_requests.csv (append only; nothing is ever deleted).
"""
import datetime as dt, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _common import clean_phone, norm, norm_address, parse_date, read_rows, write_rows  # noqa: E402
import glob

FIELDS = ["phone", "address", "owner", "date", "channel", "reason"]
OPT_OUT_SENTENCE = ("Import the latest opt-outs and do-not-contact requests from every system where your team communicates "
                    "with these owners.")
MANUAL_SENTENCE = ("Also log manual requests your employees receive (a call, letter, email or in person): add them to "
                   "suppress/manual_requests.csv or run scripts/suppression.py add.")
MANUAL_FILE = "manual_requests.csv"
MANUAL_FIELDS = FIELDS + ["logged_by", "logged_at"]
CHANNELS = ("all", "mail", "call", "sms")


def _low(r):
    return {str(k).strip().lower(): ("" if v is None else str(v).strip()) for k, v in r.items() if k}


EXPORT_DATE_COLS = ("export_date", "exported_at", "exported_on", "export_generated", "generated_at", "generated_on",
                    "report_date", "report_generated")
META_SUFFIX = ".export.json"  # written next to the CSV by `suppression.py import`
_META_LINE = re.compile(r"^\W*(?:export(?:ed)?(?:\s+(?:date|on|at))?|generated(?:\s+(?:on|at|date))?|report\s+(?:date|generated)|"
                        r"created(?:\s+on)?|run\s+date)\W*[:=,]\s*\W*([0-9][0-9/\-T: .]*)", re.I)


def _lines(path):
    for enc in ("utf-8-sig", "latin-1"):
        try:
            with open(path, newline="", encoding=enc) as f:
                return f.read().splitlines(True)
        except UnicodeDecodeError:
            continue
    raise SystemExit("Could not read " + path)


def _split_meta(path):
    """(leading metadata lines, CSV lines). Metadata = lines before the header that start with # or name a generated date."""
    lines, meta = _lines(path), []
    while lines and (lines[0].lstrip().startswith("#") or _META_LINE.match(lines[0])):
        meta.append(lines.pop(0))
    return meta, lines


def _rows(path):
    import csv, io
    _meta, body = _split_meta(path)
    return list(csv.DictReader(io.StringIO("".join(body))))


def export_date(path, today=None):
    """(date the export was generated, how we know) or (None, why not). Never uses the file's modified time."""
    today = today or dt.date.today()
    side = path + META_SUFFIX
    found, how = None, ""
    if os.path.exists(side):
        import json
        try:
            found, how = parse_date(json.load(open(side)).get("export_date")), "entered on import"
        except Exception:
            found = None
    if not found:
        meta, _body = _split_meta(path)
        for ln in meta:
            m = _META_LINE.match(ln)
            if m and parse_date(m.group(1)):
                found, how = parse_date(m.group(1)), "file header"
                break
    if not found:
        dates = [parse_date(_low(r).get(c)) for r in _rows(path) for c in EXPORT_DATE_COLS if _low(r).get(c)]
        dates = [d for d in dates if d]
        if dates:
            found, how = max(dates), "export date column"
    if not found:
        return None, "no generated date (run scripts/suppression.py import <file> --export-date YYYY-MM-DD)"
    if found > today:
        return None, f"generated date {found.isoformat()} is in the future"
    return found, how


def load(path, default_reason="", default_channel="all"):
    out = []
    if not path or not os.path.exists(path):
        return out
    for r in _rows(path):
        low = _low(r)
        ch = (low.get("channel") or default_channel).lower()
        ch = ch if ch in CHANNELS else ("sms" if "text" in ch or "sms" in ch else "call" if "call" in ch or "phone" in ch
                                        else "mail" if "mail" in ch else "all")
        row = {"phone": clean_phone(low.get("phone") or low.get("phone_number") or low.get("number")),
               "address": low.get("address") or low.get("mail_address") or low.get("mailing_address") or "",
               "owner": low.get("owner") or low.get("name") or "",
               "date": low.get("date") or low.get("added") or dt.date.today().isoformat(),
               "channel": ch, "reason": low.get("reason") or default_reason}
        if row["phone"] or norm(row["address"]) or norm(row["owner"]):
            out.append(row)
    return out


DROP_STALE_DAYS = 7


def drop_folder(folder, today=None):
    """(CSV files in the suppress/ drop folder that have rows, age in days of the newest GENERATED system export or None,
    details). Age comes from export_date(): the file header / export-date column / the date entered on import.
    manual_requests.csv is always applied but never counts as a current system export. Undated or future-dated
    exports do not count either, so a folder without a dated export in the last 7 days fails closed."""
    today = today or dt.date.today()
    info = {"dated": [], "undated": []}
    if not folder or not os.path.isdir(folder):
        return [], None, info
    files = sorted(p for p in glob.glob(os.path.join(folder, "*.csv")) if os.path.isfile(p))
    with_rows = [p for p in files if load(p)]
    for p in files:
        if os.path.basename(p) == MANUAL_FILE:
            continue
        d, how = export_date(p, today)
        if d:
            info["dated"].append((os.path.basename(p), d.isoformat(), how))
        else:
            info["undated"].append((os.path.basename(p), how))
    newest = max((dt.date.fromisoformat(d) for _n, d, _h in info["dated"]), default=None)
    age = (today - newest).days if newest else None
    return with_rows, age, info


def freshness_reason(age, info):
    """Why phones / texts are held, or '' when a current dated export exists."""
    if age is not None and age <= DROP_STALE_DAYS:
        return ""
    und = "; ".join(f"{n}: {why}" for n, why in info.get("undated", []))
    if age is None:
        return ("no system export in suppress/ with a generated date" + (f" ({und})" if und else "") +
                ". Import each export with scripts/suppression.py import <file> --export-date YYYY-MM-DD")
    return (f"the newest system export in suppress/ was generated {age} days ago (more than {DROP_STALE_DAYS})" +
            (f"; undated: {und}" if und else ""))


def import_export(src, folder, export_date_txt="", source="", by="", today=None):
    """Copy one opt-out export into suppress/ and record the date it was GENERATED (fails closed without one)."""
    import json, shutil
    today = today or dt.date.today()
    if not os.path.exists(src):
        raise SystemExit(f"File not found: {src}")
    own, how = export_date(src, today)
    entered = parse_date(export_date_txt) if export_date_txt else None
    if export_date_txt and not entered:
        raise SystemExit(f"Could not read --export-date {export_date_txt!r}. Use YYYY-MM-DD.")
    if entered and entered > today:
        raise SystemExit(f"--export-date {entered.isoformat()} is in the future. Nothing was imported.")
    if own and entered and own != entered:
        print(f"Note: the file says it was generated {own.isoformat()} ({how}); using that, not {entered.isoformat()}.")
    d = own or entered
    if not d:
        raise SystemExit("This export has no generated date in the file. Enter the date the system GENERATED it (not the "
                         "date you downloaded or copied it): --export-date YYYY-MM-DD. Nothing was imported.")
    os.makedirs(folder, exist_ok=True)
    dest = os.path.join(folder, os.path.basename(src))
    if os.path.abspath(dest) != os.path.abspath(src):
        if os.path.exists(dest):
            base, ext = os.path.splitext(dest)
            dest = f"{base}_{d.isoformat()}{ext}"
        shutil.copyfile(src, dest)
    meta = {"export_date": d.isoformat(), "how": how if own else "entered on import", "source": source, "entered_by": by,
            "imported_at": dt.datetime.now().isoformat(timespec="seconds")}
    with open(dest + META_SUFFIX, "w") as f:
        json.dump(meta, f, indent=1)
    age = (today - d).days
    print(f"Imported {dest} ({len(load(dest))} rows), generated {d.isoformat()} ({age} days ago). " +
          ("Current." if age <= DROP_STALE_DAYS else f"Older than {DROP_STALE_DAYS} days: phones and texts stay held until a newer export is imported."))
    return dest, d


def merge(master, extra=(), stop_replies=None, persist=True):
    """Merge --suppress files and STOP replies into the master list; save it (unless persist=False)."""
    rows = load(master)
    for p in extra or ():
        if p and not os.path.exists(p):
            raise SystemExit(f"Suppression file not found: {p}")
        rows += load(p)
    if stop_replies:
        if not os.path.exists(stop_replies):
            raise SystemExit(f"STOP replies file not found: {stop_replies}")
        rows += load(stop_replies, default_reason="replied STOP", default_channel="all")
    seen, out = set(), []
    for r in rows:
        k = (r["phone"], norm_address(r["address"]), norm(r["owner"]), r["channel"])
        if k in seen:
            continue
        seen.add(k)
        out.append(r)
    if persist and master:
        before = len(load(master))
        if len(out) < before:  # cumulative: never write a shorter list than the one on disk
            raise SystemExit(f"Refusing to shrink the suppression list ({before} -> {len(out)} rows). Nothing was changed.")
        write_rows(master, out, FIELDS)
    return out


def add(folder, phone="", address="", owner="", channel="all", reason="", by=""):
    """Append one manual do-not-contact request to <folder>/manual_requests.csv (append only)."""
    import csv
    if not (clean_phone(phone) or norm(address) or norm(owner)):
        raise SystemExit("Give at least one of --phone, --address or --owner.")
    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, MANUAL_FILE)
    new = not os.path.exists(path) or os.path.getsize(path) == 0
    now = dt.datetime.now().isoformat(timespec="seconds")
    with open(path, "a", newline="") as f:
        w = csv.DictWriter(f, fieldnames=MANUAL_FIELDS)
        if new:
            w.writeheader()
        w.writerow({"phone": clean_phone(phone) or "", "address": address, "owner": owner, "date": now[:10],
                    "channel": channel if channel in CHANNELS else "all", "reason": reason or "manual request", "logged_by": by,
                    "logged_at": now})
    return path


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description="Add a manual do-not-contact request (append only).")
    sub = ap.add_subparsers(dest="cmd", required=True)
    a_ = sub.add_parser("add")
    a_.add_argument("--phone", default=""); a_.add_argument("--address", default=""); a_.add_argument("--owner", default="")
    a_.add_argument("--channel", default="all", choices=CHANNELS); a_.add_argument("--reason", default="")
    a_.add_argument("--by", default="", help="who received the request")
    a_.add_argument("--folder", help="default: the kit's suppress/ folder")
    i_ = sub.add_parser("import", help="copy an opt-out export into suppress/ and record the date it was generated")
    i_.add_argument("file"); i_.add_argument("--export-date", default="", help="YYYY-MM-DD the system generated the export (required "
                                                                             "unless the file itself says)")
    i_.add_argument("--source", default="", help="which system (CRM, dialer, texting tool, mail house...)")
    i_.add_argument("--by", default="", help="who exported it")
    i_.add_argument("--folder", help="default: the kit's suppress/ folder")
    a = ap.parse_args(argv)
    folder = a.folder or os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "suppress")
    if a.cmd == "import":
        return import_export(a.file, folder, a.export_date, a.source, a.by)[0]
    path = add(folder, a.phone, a.address, a.owner, a.channel, a.reason, a.by)
    print(f"Added to {path}. It applies to every list on the next run. Rows are never removed.")
    return path


class Suppression:
    def __init__(self, rows):
        self.rows = rows or []
        self.phones = {}
        self.owners, self.addresses = [], []
        for r in self.rows:
            if r["phone"]:
                self.phones.setdefault(r["phone"], set()).add(r["channel"])
            if norm(r["owner"]):
                self.owners.append((norm(r["owner"]), r["channel"], r.get("reason", "")))
            if len(norm(r["address"])) >= 6:
                self.addresses.append((norm_address(r["address"]), r["channel"], r.get("reason", "")))

    def __len__(self):
        return len(self.rows)

    @staticmethod
    def _hit(ch, channel):
        return ch == "all" or ch == channel or channel == "any"

    def phone(self, p, channel):
        return any(self._hit(c, channel) for c in self.phones.get(clean_phone(p), ()))

    def owner(self, owner, addresses, channel):
        """Reason string if this owner (by name or any of its addresses) is suppressed for the channel."""
        no = norm(owner)
        for n, ch, why in self.owners:
            if n and n == no and self._hit(ch, channel):
                return why or "on your suppression list"
        for a in addresses:
            na = norm_address(a)
            if len(norm(a)) < 6:
                continue
            for n, ch, why in self.addresses:
                # whole-word prefix match: "123 main st" matches "123 main st raleigh nc 27606", not "1123 main st"
                if (na == n or na.startswith(n + " ") or n.startswith(na + " ")) and self._hit(ch, channel):
                    return why or "address on your suppression list"
        return ""


if __name__ == "__main__":
    main()
